#!/usr/bin/env python3
"""Lip sync bentuk mulut (viseme) dari teks naskah + suara, tanpa program luar.
Bahasa Indonesia ditulis sesuai bunyi, jadi huruf -> bentuk mulut:
  A = m/b/p (mingkem)   B = konsonan umum (sedikit buka, gigi)   C = e/i (lebar)
  D = a (mangap)        E = o (bulat)    F = u/w (monyong)    G = f/v (gigi di bibir)
  H = l/r (lidah)       X = diam
Waktu tiap huruf diatur mengikuti energi suara (bagian hening = X).
Pakai: python3 visemes.py voice.wav TOTAL lines.json > web/visemes.js
lines.json = [[frameMulai, frameAkhir, "TEKS"], ...]"""
import sys, json, wave, numpy as np
wav, total, lj = sys.argv[1], int(sys.argv[2]), sys.argv[3]
w = wave.open(wav); sr = w.getframerate(); ch = w.getnchannels()
a = np.frombuffer(w.readframes(w.getnframes()), np.int16).astype(np.float32) / 32768
if ch == 2: a = a.reshape(-1, 2).mean(1)
hop = sr / 30
env = np.array([np.sqrt(np.mean(a[int(i * hop):int((i + 1) * hop)] ** 2)) if int(i * hop) < len(a) else 0 for i in range(total)])
thr = max(0.012, np.percentile(env[env > 0], 30) * 0.6) if (env > 0).any() else 0.01
M = {**{c: 'D' for c in 'a'}, **{c: 'C' for c in 'ei'}, 'o': 'E', **{c: 'F' for c in 'uw'}, **{c: 'A' for c in 'mbp'}, **{c: 'G' for c in 'fv'}, **{c: 'H' for c in 'lr'}}
WT = {'D': 1.4, 'C': 1.2, 'E': 1.4, 'F': 1.2, 'A': 0.9, 'B': 0.7, 'G': 0.8, 'H': 0.8}
out = ['X'] * total
for f0, f1, text in json.load(open(lj)):
    t = text.lower().replace('ng', 'n').replace('ny', 'n')
    ph = [M.get(c, 'B') for c in t if c.isalpha()]
    if not ph: continue
    fr = [f for f in range(max(0, f0), min(total, f1 + 1)) if env[f] > thr]
    if not fr: continue
    wts = np.array([WT[p] for p in ph]); cum = np.concatenate([[0], np.cumsum(wts)]) / wts.sum()
    for k, f in enumerate(fr):
        u = (k + 0.5) / len(fr); i = min(len(ph) - 1, int(np.searchsorted(cum, u, side='right') - 1)); out[f] = ph[i]
# hold minimal 2 frame supaya tidak kedip
for f in range(1, total - 1):
    if out[f] != out[f - 1] and out[f] != out[f + 1] and out[f - 1] == out[f + 1]: out[f] = out[f - 1]
print('// generated by tools/visemes.py'); print('export const VIS = "' + ''.join(out) + '";')
