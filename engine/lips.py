"""Lip-sync track from a voice file: one digit per video frame (0 = closed, 1..3 = open).
Usage: python3 lips.py voice.wav TOTAL_FRAMES [offset_frames] > web/lips.js"""
import sys, wave, numpy as np
path, total = sys.argv[1], int(sys.argv[2]); off = int(sys.argv[3]) if len(sys.argv) > 3 else 0
w = wave.open(path); sr = w.getframerate(); ch = w.getnchannels()
x = np.frombuffer(w.readframes(w.getnframes()), dtype=np.int16).astype(float)
if ch > 1: x = x.reshape(-1, ch).mean(1)
x /= max(1.0, np.abs(x).max())
hop = sr / 30.0
n = int(len(x) / hop)
rms = np.array([np.sqrt(np.mean(x[int(i * hop):int((i + 1) * hop)] ** 2) + 1e-12) for i in range(n)])
db = 20 * np.log10(rms); db = np.convolve(db, [0.25, 0.5, 0.25], mode="same")
on = db > db.max() - 28
lv = np.zeros(n, int)
if on.any():
    q1, q2 = np.percentile(db[on], [35, 70])
    lv[on] = 1 + (db[on] > q1) + (db[on] > q2)
# keep it lively: a long hold flaps down every other frame
run = 0
for i in range(1, n):
    run = run + 1 if lv[i] == lv[i - 1] and lv[i] > 0 else 0
    if run >= 3 and run % 2 == 1: lv[i] = max(1, lv[i] - 1)
out = ["0"] * total
for i in range(n):
    j = i + off
    if 0 <= j < total: out[j] = str(lv[i])
print('// generated by tools/lips.py from %s\nexport const LIPS = "%s";' % (path.split("/")[-1], "".join(out)))
